package config

import (
	"testing"
	"time"
)

func TestLoadDefaults(t *testing.T) {
	for _, k := range []string{"PURSAE_ADDR", "DATABASE_URL", "PURSAE_SITE_URL", "PURSAE_UPLOADS_DIR", "PURSAE_DEV_HUB_URL", "PURSAE_SMTP_PORT", "PURSAE_SECRET", "PURSAE_WEB_DIR"} {
		t.Setenv(k, "")
	}
	c := Load()
	if c.Addr != ":8080" || c.UploadsDir != "./data/uploads" || c.SMTPPort != "587" {
		t.Errorf("defaults changed: %+v", c)
	}
	if c.SiteURL != "http://localhost:8080" {
		t.Errorf("SiteURL = %q", c.SiteURL)
	}
	if c.Secret != "" || c.WebDir != "" {
		t.Errorf("Secret and WebDir must stay empty unless set: %+v", c)
	}
	if c.HubURL != "https://hub.pursae.com" {
		t.Errorf("HubURL = %q, want https://hub.pursae.com", c.HubURL)
	}
}

func TestLoadTrimsTrailingSlashes(t *testing.T) {
	t.Setenv("PURSAE_SITE_URL", "https://example.com///")
	c := Load()
	if c.SiteURL != "https://example.com" {
		t.Errorf("SiteURL = %q", c.SiteURL)
	}
}

func TestHubOff(t *testing.T) {
	for v, off := range map[string]bool{"": false, "on": false, "https://x.example": false, "off": true, "OFF": true, " none ": true, "0": true, "false": true, "no": true} {
		t.Setenv("PURSAE_HUB", v)
		c := Load()
		if c.HubOff != off || (off && c.HubURL != "off") || (!off && c.HubURL == "off") {
			t.Errorf("PURSAE_HUB=%q: HubOff=%v HubURL=%q", v, c.HubOff, c.HubURL)
		}
	}
}

func TestSetupToken(t *testing.T) {
	t.Setenv("PURSAE_SETUP_TOKEN", "")
	if c := Load(); c.SetupToken != "" {
		t.Errorf("SetupToken = %q, want empty (generated by the server)", c.SetupToken)
	}
	t.Setenv("PURSAE_SETUP_TOKEN", "  s3cret-token \n")
	if c := Load(); c.SetupToken != "s3cret-token" {
		t.Errorf("SetupToken = %q", c.SetupToken)
	}
}

func TestParseSlowQuery(t *testing.T) {
	for in, want := range map[string]time.Duration{
		"": 0, "0": 0, "-5": 0, "abc": 0, "250": 250 * time.Millisecond, "250ms": 250 * time.Millisecond, "1s": time.Second, "-1s": 0,
	} {
		if got := parseSlowQuery(in); got != want {
			t.Errorf("parseSlowQuery(%q) = %v, want %v", in, got, want)
		}
	}
}
