#!/usr/bin/env bash
# Builds the example wpgo plugins into signed packages:
#
#   examples/plugins/dist/<slug>-<version>.zip
#
# Each plugin is compiled with GOOS=wasip1 GOARCH=wasm -buildmode=c-shared
# (a WASI "reactor": the host calls _initialize, then the wpgo_* exports),
# packed with its plugin.json, readme.md, icon.svg and assets/ directory, and
# signed with an Ed25519 key. If examples/plugins/dist/dev-key.key does not
# exist, a DEVELOPMENT key pair is generated there. Never trust the dev key in
# production; use your own key via WPGO_SIGNING_KEY=/path/to/key.
#
# Usage: tools/build-plugins.sh [plugin-dir ...]
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

dist="examples/plugins/dist"
mkdir -p "$dist"

pkgtool="$dist/.wpgo-pkg"
go build -o "$pkgtool" ./internal/plugins/cmd/wpgo-pkg

key="${WPGO_SIGNING_KEY:-$dist/dev-key.key}"
pub="${key%.key}.pub"
if [[ -z "${WPGO_SIGNING_KEY:-}" ]]; then
  "$pkgtool" keygen -out "$dist/dev-key" \
    -comment "DEVELOPMENT KEY - generated by tools/build-plugins.sh.
Do not use it to sign plugins for production sites and do not add it to a production trust list."
fi

if [[ $# -gt 0 ]]; then
  plugins=("$@")
else
  plugins=(examples/plugins/hello-gopher examples/plugins/word-counter examples/plugins/shortcode-demo)
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

for dir in "${plugins[@]}"; do
  dir="${dir%/}"
  slug="$(sed -n 's/.*"slug"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$dir/plugin.json" | head -n1)"
  version="$(sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$dir/plugin.json" | head -n1)"
  echo "==> $slug $version"
  GOOS=wasip1 GOARCH=wasm CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -buildmode=c-shared \
    -o "$tmp/$slug.wasm" "./$dir"
  "$pkgtool" pack -dir "$dir" -wasm "$tmp/$slug.wasm" -key "$key" -out "$dist/$slug-$version.zip"
  if [[ -f "$pub" ]]; then
    "$pkgtool" verify -pub "$pub" "$dist/$slug-$version.zip"
  fi
done

rm -f "$pkgtool"
echo "packages in $dist"
